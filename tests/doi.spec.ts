import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const crossref = JSON.parse(readFileSync(new URL('./fixtures/crossref.json', import.meta.url), 'utf8'));
const datacite = JSON.parse(readFileSync(new URL('./fixtures/datacite.json', import.meta.url), 'utf8'));

test('looks up DOI, reviews metadata, switches styles and updates all citations on edit', async ({ page }) => {
 const errors: string[]=[];page.on('pageerror',e=>errors.push(e.message));
 let requests=0;
 await page.route('https://api.crossref.org/**', async route => {requests++; await route.fulfill({json:crossref});});
 await page.goto('/');
 await page.getByRole('button',{name:'Nuevo documento'}).click();await page.getByPlaceholder('Mi próxima gran idea').fill('Tesis DOI');await page.getByRole('button',{name:'Crear documento'}).click();
 await page.locator('.tiptap p').last().click();
 await page.getByRole('button',{name:'Referencias',exact:true}).click();
 await page.getByLabel('Enlace o DOI',{exact:true}).fill('10.1038/nphys1170');
 await page.getByRole('button',{name:'Buscar datos por DOI'}).click();
 await expect(page.getByLabel('Título de la fuente',{exact:true})).toHaveValue('Measured measurement');
 await expect(page.getByRole('status').filter({hasText:'Datos recuperados de Crossref'})).toBeVisible();
 await page.getByRole('combobox',{name:'Estilo bibliográfico'}).selectOption('apa');
 await page.getByRole('button',{name:'Guardar e insertar cita'}).click();
 const citation=page.locator('.tiptap .citation');
 await expect(citation).toHaveAttribute('data-citation-label','(Aspelmeyer, 2009)');
 await expect(page.locator('.bibliography')).toContainText('Aspelmeyer, M. (2009)');
 await expect(page.locator('.bibliography i').first()).toHaveText('Nature Physics');
 await page.getByRole('button',{name:'Referencias',exact:true}).click();
 await page.getByRole('combobox',{name:'Estilo bibliográfico'}).selectOption('ieee');
 await expect(citation).toHaveAttribute('data-citation-label','[1]');
 await page.getByRole('combobox',{name:'Estilo bibliográfico'}).selectOption('vancouver');
 await expect(citation).toHaveAttribute('data-citation-label','(1)');
 await page.getByRole('button',{name:'Editar Measured measurement'}).click();
 await page.getByLabel('Título de la fuente',{exact:true}).fill('Título revisado');
 await page.getByRole('button',{name:'Guardar cambios'}).click();
 await expect(page.locator('.bibliography')).toContainText('Título revisado');
 await page.getByRole('combobox',{name:'Estilo bibliográfico'}).selectOption('apa');
 await page.getByRole('button',{name:'Cerrar',exact:true}).click();
 await page.waitForTimeout(600);await page.reload();
 await page.getByRole('button',{name:'Tesis DOI Guardado en este dispositivo'}).click();
 await expect(citation).toHaveAttribute('data-citation-label','(Aspelmeyer, 2009)');
 await expect(page.locator('.bibliography')).toContainText('Título revisado');
 await page.getByRole('button',{name:'LaTeX AUTO'}).click();
 await expect(page.locator('.latex-panel pre')).toContainText('\\textit{Nature Physics}');
 expect(requests).toBe(1);expect(errors).toEqual([]);
});
test('DataCite fallback reports missing fields; 429 and network errors preserve manual input', async ({page})=>{
 await page.route('https://api.crossref.org/**',route=>route.fulfill({status:404,json:{}}));
 await page.route('https://api.datacite.org/**',route=>route.fulfill({json:datacite}));
 await page.goto('/');await page.getByRole('button',{name:'Referencias',exact:true}).click();
 await page.getByLabel('Enlace o DOI',{exact:true}).fill('10.5281/zenodo.3242077');await page.getByRole('button',{name:'Buscar datos por DOI'}).click();
 await expect(page.getByRole('status').filter({hasText:'DataCite'})).toContainText('Faltan: revista');
 await page.getByLabel('Enlace o DOI',{exact:true}).fill('10.1000/rate');
 await page.route('https://api.crossref.org/**',route=>route.fulfill({status:429,json:{}}));
 await page.getByRole('button',{name:'Buscar datos por DOI'}).click();await expect(page.getByRole('alert')).toContainText('limitado');
 await page.getByLabel('Título de la fuente',{exact:true}).fill('Entrada manual');
 await page.route('https://api.crossref.org/**',route=>route.abort());
 await page.getByRole('button',{name:'Buscar datos por DOI'}).click();await expect(page.getByRole('alert')).toContainText('conectar');
 await expect(page.getByLabel('Título de la fuente',{exact:true})).toHaveValue('Entrada manual');
});
test('changing DOI cancels stale results and does not replace the new form',async({page})=>{
 let release:()=>void=()=>{};const pending=new Promise<void>(resolve=>{release=resolve});
 await page.route('https://api.crossref.org/**',async route=>{await pending;await route.fulfill({json:crossref}).catch(()=>{});});
 await page.goto('/');await page.getByRole('button',{name:'Referencias',exact:true}).click();
 await page.getByLabel('Enlace o DOI',{exact:true}).fill('10.1038/nphys1170');await page.getByRole('button',{name:'Buscar datos por DOI'}).click();
 await expect(page.getByRole('button',{name:'Buscando en los registros…'})).toBeVisible();
 await page.getByLabel('Enlace o DOI',{exact:true}).fill('10.1000/new');
 release();await page.getByLabel('Título de la fuente',{exact:true}).fill('Mi nueva fuente');
 await expect(page.getByLabel('Título de la fuente',{exact:true})).toHaveValue('Mi nueva fuente');
 await expect(page.getByLabel('Enlace o DOI',{exact:true})).toHaveValue('10.1000/new');
});
