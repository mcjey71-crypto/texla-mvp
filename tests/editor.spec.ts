import { test, expect } from '@playwright/test';
test('visual editor, AI equations, persistence and export', async ({ page }) => {
 const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
 await page.goto('/');
 await expect(page.locator('.tiptap h1')).toHaveText('El lenguaje del universo');
 await page.screenshot({ path: '/workspace/texla-desktop.png', fullPage: true });
 await page.getByRole('button', { name: 'Nuevo documento' }).click();
 await page.getByPlaceholder('Mi próxima gran idea').fill('Tesis de prueba');
 await page.getByRole('button', { name: 'Crear documento' }).click();
 await expect(page.locator('.tiptap h1')).toHaveText('Tesis de prueba');
 await page.locator('.tiptap p').last().click();
 await page.getByRole('button', { name: 'Pegar contenido' }).click();
 await page.getByRole('button', { name: 'Probar un ejemplo' }).click();
 await page.getByRole('button', { name: 'Insertar contenido' }).click();
 await expect(page.locator('.tiptap .katex')).toHaveCount(1);
 await expect(page.getByText('Guardado en este navegador').first()).toBeVisible();
 await page.waitForTimeout(600);
 await page.reload();
 // First document is selected on reload; switch to persisted newly created document.
 await page.getByRole('button', { name: 'Tesis de prueba Guardado en este dispositivo' }).click();
 await expect(page.locator('.tiptap .katex')).toHaveCount(1);
 await page.getByRole('button', { name: 'Exportar', exact: true }).click();
 const download = page.waitForEvent('download');
 await page.getByRole('button', { name: 'Documento LaTeX' }).click();
 expect((await download).suggestedFilename()).toBe('Tesis de prueba.tex');
 await page.getByRole('button', { name: 'Cerrar', exact: true }).click();
 await page.getByRole('button', { name: 'Ecuación', exact: true }).click();
 await page.getByRole('button', { name: 'Fracción', exact: false }).click();
 await expect(page.locator('math-field')).toBeVisible();
 await page.getByRole('button', { name: 'Insertar ecuación' }).click();
 await expect(page.locator('.tiptap .katex')).toHaveCount(2);
 expect(errors).toEqual([]);
});
test('mobile layout fits viewport and navigation works', async ({ page }) => {
 await page.setViewportSize({ width: 390, height: 844 }); await page.goto('/');
 await expect(page.locator('.tiptap h1')).toBeVisible();
 expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
 await page.screenshot({ path: '/workspace/texla-mobile.png', fullPage: true });
 await page.getByRole('button', { name: 'Abrir menú' }).click();
 await expect(page.getByRole('button', { name: 'Nuevo documento' })).toBeVisible();
});
test('native clipboard preserves inline and block equations; undo is isolated per document', async ({ page, context }) => {
 await context.grantPermissions(['clipboard-read', 'clipboard-write']); await page.goto('/');
 await page.getByRole('button', { name: 'Nuevo documento' }).click();
 await page.getByPlaceholder('Mi próxima gran idea').fill('Pegado directo');
 await page.getByRole('button', { name: 'Crear documento' }).click();
 await page.locator('.tiptap p').last().click();
 await page.evaluate(() => navigator.clipboard.writeText('Energía: \\(E=mc^2\\)\n\\[\\frac{a}{b}\\]'));
 await page.keyboard.press('Control+V');
 await expect(page.locator('.tiptap .katex')).toHaveCount(2);
 await page.locator('.tiptap [data-type="block-math"]').click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await page.getByText('Editar código LaTeX (opcional)').click();
 await page.getByRole('textbox', { name: 'Código LaTeX' }).fill('x^3');
 await page.getByRole('button', { name: 'Guardar ecuación' }).click();
 await expect(page.locator('.tiptap [data-type="block-math"]')).toHaveAttribute('data-latex', 'x^3');
 await page.getByRole('button', { name: 'El lenguaje del universo Tu primer documento' }).click();
 await page.getByRole('button', { name: 'Deshacer', exact: true }).click();
 await expect(page.locator('.tiptap h1')).toHaveText('El lenguaje del universo');
});
