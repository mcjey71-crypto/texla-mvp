import { test, expect } from '@playwright/test';
test('visual editor, AI equations, persistence and export', async ({ page }) => {
 const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
 await page.goto('/');
 await expect(page.locator('.tiptap h1')).toHaveText('El lenguaje del universo');
 await page.screenshot({ path: '/workspace/texla-desktop.png', fullPage: true });
 await page.getByRole('button', { name: 'Nuevo documento' }).click();
 await page.getByPlaceholder('Mi próxima gran idea').fill('Tesis de prueba');
 await page.getByRole('button', { name: 'Crear documento' }).click();
 await expect(page.locator('.tiptap h1')).toHaveText('Tesis de prueba');
 await page.locator('.tiptap p').last().click();
 await page.getByRole('button', { name: 'Pegar contenido' }).click();
 await page.getByRole('button', { name: 'Probar un ejemplo' }).click();
 await page.getByRole('button', { name: 'Insertar contenido' }).click();
 await expect(page.locator('.tiptap .katex')).toHaveCount(1);
 await expect(page.getByText('Guardado en este navegador').first()).toBeVisible();
 await page.waitForTimeout(600);
 await page.reload();
 // First document is selected on reload; switch to persisted newly created document.
 await page.getByRole('button', { name: 'Tesis de prueba Guardado en este dispositivo' }).click();
 await expect(page.locator('.tiptap .katex')).toHaveCount(1);
 await page.getByRole('button', { name: 'Exportar', exact: true }).click();
 const download = page.waitForEvent('download');
 await page.getByRole('button', { name: 'Documento LaTeX' }).click();
 expect((await download).suggestedFilename()).toBe('Tesis de prueba.tex');
 await page.getByRole('button', { name: 'Cerrar', exact: true }).click();
 await page.getByRole('button', { name: 'Ecuación', exact: true }).click();
 await page.getByRole('button', { name: 'Fracción', exact: false }).click();
 await expect(page.locator('math-field')).toBeVisible();
 await page.getByRole('button', { name: 'Insertar ecuación' }).click();
 await expect(page.locator('.tiptap .katex')).toHaveCount(2);
 expect(errors).toEqual([]);
});
